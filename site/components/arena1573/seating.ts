export const sectionDoors: Record<SeatingVenue, { id: number; x: number; z: number }[]> = {
  rla: rodLaverDoors, mca: [], john: [],
};

// Area-weighted centres keep the 3D sightline aligned with the same bay
// selected on the plan, including multi-part sections.
function centroid(footprints: Point[][]): Point {
  let x = 0, z = 0, weight = 0;
  for (const polygon of footprints) {
    let area = 0, px = 0, pz = 0;
    polygon.forEach((a, i) => {
      const b = polygon[(i + 1) % polygon.length];
      const wedge = a.x * b.z - b.x * a.z;
      area += wedge;
      px += (a.x + b.x) * wedge;
      pz += (a.z + b.z) * wedge;
    });
    x += Math.sign(area) * px;
    z += Math.sign(area) * pz;
    weight += Math.abs(area) * 3;
  }
  return { x: x / weight, z: z / weight };
}

function tierFor(venue: SeatingVenue, id: SectionId): SeatingTier {
  if (typeof id === 'string') return 'courtside';
  if (venue === 'john') return id <= 20 ? 'lower' : id <= 48 ? 'middle' : 'upper';
  return id < 20 ? 'lower' : 'upper';
}

function hydrateBays(venue: SeatingVenue, measurements: MeasuredBay[]): SeatSection[] {
  return measurements.map(([id, blocks, interiorAnchor]) => {
    const footprints = blocks.split(' | ').map(block => block.split(' ').map(pair => {
      const [x, z] = pair.split(',').map(Number);
      return { x: x / 100, z: z / 100 };
    }));
    // A marked interior anchor keeps the sample seat clear of a corner aisle.
    const centre = interiorAnchor ? { x: interiorAnchor[0] / 100, z: interiorAnchor[1] / 100 } : centroid(footprints);
    const { x, z } = centre;
    const side: SeatingSide = Math.abs(x) > Math.abs(z)
      ? (x > 0 ? 'east' : 'west') : (z > 0 ? 'south' : 'north');
    const nearby = sectionDoors[venue].reduce<(typeof rodLaverDoors)[number] | undefined>((best, door) => {
      const distance = (p: Point) => Math.hypot(x - p.x, z - p.z);
      return !best || distance(door) < distance(best) ? door : best;
    }, undefined);
    const sunMarked = typeof id === 'number' && (
      (venue === 'rla' && ((id >= 3 && id <= 8) || (id >= 12 && id <= 17) || (id >= 25 && id <= 33) || (id >= 44 && id <= 50))) ||
      (venue === 'mca' && ((id >= 3 && id <= 8) || (id >= 12 && id <= 18) || (id >= 23 && id <= 27) || (id >= 34 && id <= 38)))
    );
    return { id, footprints, ...centre, tier: tierFor(venue, id), side, nearbyDoor: nearby?.id, sunMarked };
  });
}

export const seatSections: Record<SeatingVenue, SeatSection[]> = {
  rla: hydrateBays('rla', rodLaver),
  mca: hydrateBays('mca', margaretCourt),
  john: hydrateBays('john', johnCain),
};

export function baselineSection(venue:SeatingVenue){
  const sections=seatSections[venue];
  return sections.filter(s=>s.side==='south'&&s.tier==='lower')
    .sort((a,b)=>Math.abs(a.x)-Math.abs(b.x))[0]??sections[0];
}

export function sectionPosition(venue: SeatingVenue, id: SectionId) {
  const section = seatSections[venue].find(section => section.id === id);
  if (!section) return undefined;
  return { x: section.x, z: section.z, level: levels[section.tier] };
}
