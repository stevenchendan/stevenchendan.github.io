export type SeatingVenue = 'rla' | 'mca' | 'john';
export type SectionId = number | string;
export type SeatingTier = 'courtside' | 'lower' | 'middle' | 'upper';
export type SeatingSide = 'north' | 'east' | 'south' | 'west';
type Point = { x: number; z: number };
export type SeatSection = Point & {
  id: SectionId;
  side: SeatingSide;
  tier: SeatingTier;
  footprints: Point[][];
  nearbyDoor?: number;
  sunMarked: boolean;
};

